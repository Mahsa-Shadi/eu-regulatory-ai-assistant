import streamlit as st
from rag import retrieve, generate_answer, LLMError, is_refusal, verify_answer



st.title("EU Regulatory AI Assistant")

question = st.text_input("Ask your question:")

if st.button("Ask"):

    if not question.strip():
        st.warning("Please enter a question.")

    else:
        try:
            with st.spinner("Generating answer..."):
                answer, context = generate_answer(question)
        except LLMError:
            st.error("The language model is currently unavailable. Please try again.")
            answer = None

        if answer:
            st.subheader("Answer")
            st.write(answer)

            if is_refusal(answer):
                st.write("Verdict: REFUSAL")

            else:
                try:
                    with st.spinner("Verifying answer..."):
                        verdict, explanation = verify_answer(answer, context)

                    st.write("Verdict:", verdict)
                    st.write("Explanation:", explanation)
                    st.caption("Verdict generated by an LLM judge; not independently validated.")

                except LLMError:
                    st.warning("Answer verification is currently unavailable.")

        results = retrieve(question)


        for chunk_id, document, distance in results:
            st.subheader(f"{chunk_id}, distance {distance:.3f}")
            with st.expander(f'{chunk_id} details : '):
                st.write(document)